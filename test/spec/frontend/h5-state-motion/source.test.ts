// DSX-48 / DSX-108: reduced-motion and forced-colors rules exist in apps/h5's global styles and in
// a generated CSS file of @couli/ui-tokens that apps/h5 imports; pages and components of apps/h5
// never write milliseconds or Bézier values themselves (规划/03 §10.6: "页面与组件里不写死毫秒数
// 和贝塞尔值，一律取上表变量"). The couli-style lint rules do not cover transition / animation, so
// the sources are scanned here: CSS without comments, TS / TSX only in string and JSX text parts
// (class lists, inline styles), so comments and identifiers never count.
import ts from 'typescript';
import { expect, it } from 'vitest';
import { MIN_VISIBLE_MS, SHIMMER_MS, SHOW_DELAY_MS, SYSTEM_COLOR } from './expected.ts';
import {
  filesUnder,
  nonEmptyMedia,
  record,
  requiredJson,
  requiredText,
  withoutComments,
} from './kit.ts';

const H5_STYLES = 'apps/h5/src/shared/styles/index.css';
const REDUCED = /\(\s*prefers-reduced-motion\s*:\s*reduce\s*\)/;
const FORCED = /\(\s*forced-colors\s*:\s*active\s*\)/;

function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
}

it('[AC-DSX-48-A11Y-CSS#1] apps/h5 全局样式与 ui-tokens 生成的 CSS 都有 prefers-reduced-motion: reduce 与 forced-colors: active 规则（后者用系统色），且 H5 引入了该生成文件', () => {
  const h5 = requiredText(H5_STYLES);
  const h5Reduced = nonEmptyMedia(h5, REDUCED);
  expect(h5Reduced, `${H5_STYLES}: @media (prefers-reduced-motion: reduce)`).not.toEqual([]);
  expect(
    nonEmptyMedia(h5, FORCED).some((body) => SYSTEM_COLOR.test(body)),
    `${H5_STYLES}: @media (forced-colors: active) with system colours`,
  ).toBe(true);

  // tokens.gen.css must keep only its three token blocks (tokens.test.ts, TOKENS#3), so the rules
  // live in another generated file of the package, exported as a CSS subpath.
  const generated = filesUnder('packages/ui-tokens/src').filter((file) =>
    file.endsWith('.gen.css'),
  );
  const reduced = generated.filter((file) => nonEmptyMedia(requiredText(file), REDUCED).length > 0);
  const forced = generated.filter((file) =>
    nonEmptyMedia(requiredText(file), FORCED).some((body) => SYSTEM_COLOR.test(body)),
  );
  expect(reduced, 'ui-tokens generated CSS with prefers-reduced-motion: reduce').not.toEqual([]);
  expect(forced, 'ui-tokens generated CSS with forced-colors: active').not.toEqual([]);

  const exportsMap = record(requiredJson('packages/ui-tokens/package.json').exports, 'exports');
  for (const file of new Set([...reduced, ...forced])) {
    expect(requiredText(file).split('\n')[0], `${file} header`).toContain(
      'Generated by @couli/ui-tokens',
    );
    const target = `./${file.slice('packages/ui-tokens/'.length)}`;
    const subpaths = Object.entries(exportsMap)
      .filter(([, value]) => value === target)
      .map(([key]) => key);
    expect(subpaths, `packages/ui-tokens/package.json exports ${target}`).not.toEqual([]);
    const imported = subpaths.some((subpath) => {
      const specifier = `@couli/ui-tokens${escapeRegExp(subpath.slice(1))}`;
      return new RegExp(`@import\\s+(['"])${specifier}\\1`).test(withoutComments(h5));
    });
    expect(imported, `${H5_STYLES} imports ${file}`).toBe(true);
  }
});

interface Rule {
  name: string;
  test: (text: string) => boolean;
}

/** Digits followed by ms, in any string part. */
const MILLISECONDS = /(?:^|[^\w.-]|_)\.?\d+(?:\.\d+)?ms(?![a-zA-Z0-9])/;
/** Digits followed by ms or s, inside one Tailwind [arbitrary] value (`_` separates words). */
const ARBITRARY_TIME = /(?:^|[^\w.-]|_)\.?\d+(?:\.\d+)?m?s(?![a-zA-Z0-9])/;
const ARBITRARY_VALUE = /\[([^\]]*)\]/g;
const BEZIER = /cubic-bezier\(/;
const TAILWIND_DURATION = /(?:^|[\s:"'`[(])(?:duration|delay)-\d/;
const TAILWIND_EASE = /(?:^|[\s:"'`[(])ease-\[/;
const PULSE = /(?:^|[\s:"'`])animate-pulse\b/;
/** Digits followed by ms or s in CSS (comments removed). */
const CSS_TIME = /(?:^|[^\w.-])\.?\d+(?:\.\d+)?m?s(?![\w-])/;

function arbitraryTime(text: string): boolean {
  return [...text.matchAll(ARBITRARY_VALUE)].some(([, inner]) => ARBITRARY_TIME.test(inner ?? ''));
}

const STRING_RULES: readonly Rule[] = [
  { name: 'milliseconds', test: (text) => MILLISECONDS.test(text) },
  { name: 'cubic-bezier()', test: (text) => BEZIER.test(text) },
  { name: 'Tailwind duration-* / delay-* number', test: (text) => TAILWIND_DURATION.test(text) },
  { name: 'Tailwind ease-[…]', test: (text) => TAILWIND_EASE.test(text) },
  { name: 'time inside a Tailwind arbitrary value', test: arbitraryTime },
  // The skeleton shimmers now (规划/03 §10.6 item 7); the old breathing pulse is gone.
  { name: 'animate-pulse', test: (text) => PULSE.test(text) },
];

const CSS_RULES: readonly Rule[] = [
  { name: 'time literal', test: (text) => CSS_TIME.test(text) },
  { name: 'cubic-bezier()', test: (text) => BEZIER.test(text) },
];

/** Skeleton timings must come from the tokens, not from number literals in shared H5 code. */
const TIMING_NUMBERS = new Set([SHOW_DELAY_MS, MIN_VISIBLE_MS, SHIMMER_MS]);
const SHARED_CODE = ['apps/h5/src/components/base/', 'apps/h5/src/shared/'];

/** String, template and JSX text parts, and number literals of a TS / TSX source. */
function literalParts(file: string, source: string): { strings: string[]; numbers: number[] } {
  const kind = file.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  const tree = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, kind);
  const strings: string[] = [];
  const numbers: number[] = [];
  const visit = (node: ts.Node): void => {
    if (
      ts.isStringLiteral(node) ||
      ts.isNoSubstitutionTemplateLiteral(node) ||
      ts.isTemplateHead(node) ||
      ts.isTemplateMiddle(node) ||
      ts.isTemplateTail(node) ||
      ts.isJsxText(node)
    ) {
      strings.push(node.text);
    } else if (ts.isNumericLiteral(node)) {
      numbers.push(Number(node.text.replaceAll('_', '')));
    }
    ts.forEachChild(node, visit);
  };
  visit(tree);
  return { strings, numbers };
}

it('[AC-DSX-48-NO-HARDCODE#1] apps/h5/src 的页面与组件不写死毫秒数、贝塞尔值与 Tailwind 时长类，骨架不再用 animate-pulse，共用代码不写死骨架时长', () => {
  const sources = filesUnder('apps/h5/src').filter(
    (file) =>
      /\.(?:ts|tsx|css)$/.test(file) && !/\.test\.tsx?$/.test(file) && !/\.gen\./.test(file),
  );
  expect(sources).toContain('apps/h5/src/components/base/Skeleton.tsx');
  expect(sources).toContain(H5_STYLES);
  const violations: string[] = [];
  for (const file of sources) {
    const source = requiredText(file);
    if (file.endsWith('.css')) {
      const css = withoutComments(source);
      for (const rule of CSS_RULES) {
        for (const line of css.split('\n')) {
          if (rule.test(line)) violations.push(`${file}: ${rule.name}: ${line.trim()}`);
        }
      }
      continue;
    }
    const { strings, numbers } = literalParts(file, source);
    for (const text of strings) {
      for (const rule of STRING_RULES) {
        if (rule.test(text)) violations.push(`${file}: ${rule.name}: ${JSON.stringify(text)}`);
      }
    }
    if (SHARED_CODE.some((prefix) => file.startsWith(prefix))) {
      for (const value of numbers) {
        if (TIMING_NUMBERS.has(value)) violations.push(`${file}: skeleton timing literal ${value}`);
      }
    }
  }
  expect(violations).toEqual([]);
});
