import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { afterEach, expect, it } from 'vitest';
import {
  FAKE_CLAUDE,
  TASK,
  TOOLS_DIR,
  gitIn,
  installLoggedState,
  makeFixture,
  runScript,
  trustedState,
  trustedTaskState,
  writeStub,
  type Fixture,
} from '../../../../../tools/agent/testing/fixture.ts';
import { parseTaskFile, type TaskFile } from '../../../../../tools/lib/task-file.ts';

const LEDGER = `ops/tasks/${TASK}.yaml`;
const TEST_DIR = 'test/spec/demo/companion';
const LONG = { timeout: 60_000 };
const wrappers = [
  { script: 'codex-run.sh', engine: 'codex' },
  { script: 'claude-run.sh', engine: 'claude-independent' },
] as const;

const confirmationFields = [
  'red_exempt',
  'red_exempt_outside',
  'renames',
  'expected_values',
] as const;
type Declarations = { [Field in (typeof confirmationFields)[number]]: TaskFile[Field][number] };

const fixtures: Fixture[] = [];

afterEach(() => {
  for (const fx of fixtures.splice(0)) fx.cleanup();
});

function fixture(): Fixture {
  const fx = makeFixture('trusted-confirm-round');
  fixtures.push(fx);
  fx.env['COULI_CLAUDE_BIN'] = FAKE_CLAUDE;
  gitIn(fx.trusted, ['init', '-q', '-b', 'trusted-ledger']);
  // The parser and review validator need these guard files in the trusted root.
  cpSync(join(TOOLS_DIR, 'guard', 'lib'), join(fx.trusted, 'tools', 'guard', 'lib'), {
    recursive: true,
  });
  cpSync(
    join(TOOLS_DIR, 'guard', 'protected-paths.json'),
    join(fx.trusted, 'tools', 'guard', 'protected-paths.json'),
  );
  return fx;
}

function declarations(key: string, revision = 1): Declarations {
  const reason = `Existing coverage passes at the base, revision ${revision}`;
  return {
    red_exempt: { file: `${TEST_DIR}/check.test.ts`, test: `frozen check ${key}`, reason },
    red_exempt_outside: { file: `${TEST_DIR}/outside-${key}.test.ts`, reason },
    renames: { from: `'legacy-${key}'`, to: `'updated-${key}-v${revision}'` },
    expected_values: {
      file: `${TEST_DIR}/defaults.test.ts`,
      helper: 'makeDefaults',
      from: `${key}Limit: 700,`,
      to: `${key}Limit: ${700 + revision},`,
    },
  };
}

function distinguishingKeys(entry: Declarations): string[] {
  return [
    entry.red_exempt.test,
    entry.red_exempt_outside.file,
    entry.renames.from,
    entry.expected_values.from,
  ];
}

function writeLedger(root: string, title: string, entries: readonly Declarations[]): string {
  const sections = confirmationFields.flatMap((field) =>
    entries.length === 0
      ? []
      : [
          `${field}:`,
          ...entries.flatMap((entry) =>
            Object.entries(entry[field]).map(([name, value], index) => {
              const indent = index === 0 ? '  - ' : '    ';
              return `${indent}${name}: ${JSON.stringify(value)}`;
            }),
          ),
        ],
  );
  const contents = [
    `id: ${TASK}`,
    'repo: rebate-platform',
    `title: ${title}`,
    'type: impl',
    'refs: []',
    'refs_hash: {}',
    'deps: []',
    'paths: [src/a.ts]',
    `test_paths: [${TEST_DIR}/**]`,
    'impl: claude',
    'tester: claude-independent',
    'accept: [pnpm verify:fast]',
    'status: todo',
    ...sections,
    '',
  ].join('\n');
  const file = join(root, LEDGER);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, contents);
  return contents;
}

function commitLedger(fx: Fixture, title: string, entries: readonly Declarations[] = []): string {
  const task = parseTaskFile(writeLedger(fx.trusted, title, entries), LEDGER);
  gitIn(fx.trusted, ['add', '--', LEDGER]);
  gitIn(fx.trusted, ['commit', '-q', '-m', title]);
  // RV1 lets a general review reach the confirmation flag check.
  writeStub(join(fx.trusted, 'tools', 'ops', 'task.ts'), 'task', [
    { when: ['show'], stdout: JSON.stringify({ ...task, risk: 'RV1' }) },
  ]);
  return gitIn(fx.trusted, ['rev-parse', 'HEAD']);
}

function confirmationContext(fx: Fixture, script: string, baseline: string): string {
  const result = runScript(
    script,
    [
      'review',
      TASK,
      '--base',
      fx.baseSha,
      '--review-type',
      'spec-test',
      '--confirm-round',
      baseline,
      '--dry-run',
    ],
    fx.env,
  );
  expect(result.status, result.stderr).toBe(0);
  const lastArg = result.stdout.trimEnd().split('\n').at(-1) ?? '';
  const prompt = lastArg.replace(/\\(\\|n)/g, (_, c: string) => (c === 'n' ? '\n' : c));
  const [, context = ''] = prompt.split('\n## Review context (generated by ');
  const [facts = ''] = context.split('\n### ');
  expect(facts).toContain('\n- Confirmation round: yes\n');
  return facts;
}

it.each(wrappers)(
  '[AC-CT-06zzzzzzzm#1] $script reports declaration changes since the supplied trusted baseline',
  LONG,
  ({ script }) => {
    const fx = fixture();
    const original = declarations('changed');
    const retained = declarations('retained');
    const removed = declarations('removed');
    const added = declarations('added');
    const changed = declarations('changed', 2);
    const worktreeOnly = declarations('worktreeOnly');
    // Comparing with the first ledger revision would count the retained group as added.
    commitLedger(fx, 'First ledger', [original, removed]);
    const baseline = commitLedger(fx, 'Baseline ledger', [original, retained, removed]);
    // A comparison with the immediately preceding commit would miss the added group.
    commitLedger(fx, 'Intermediate ledger', [original, retained, removed, added]);
    commitLedger(fx, 'Current ledger with a new title', [changed, retained, added]);
    writeLedger(fx.worktree, 'Worktree ledger', [worktreeOnly]);

    const context = confirmationContext(fx, script, baseline);
    expect(context).toContain(
      '- Declarations added or changed this round: 8 entries ' +
        '(red_exempt 2, red_exempt_outside 2, renames 2, expected_values 2)',
    );
    for (const key of [added, changed].flatMap(distinguishingKeys)) {
      expect(context).toContain(key);
    }
    for (const key of [retained, removed, worktreeOnly].flatMap(distinguishingKeys)) {
      expect(context).not.toContain(key);
    }
  },
);

it.each(wrappers)(
  '[AC-CT-06zzzzzzzm#2] $script rejects code review confirmations with a valid baseline and refunds each round',
  LONG,
  ({ script, engine }) => {
    const fx = fixture();
    const baseline = commitLedger(fx, 'Baseline ledger');
    commitLedger(fx, 'Current ledger');
    installLoggedState(fx);

    confirmationContext(fx, script, baseline);

    for (const reviewType of [undefined, 'general', 'money', 'contract']) {
      const reviewArgs = reviewType === undefined ? [] : ['--review-type', reviewType];
      const bump = trustedState(fx, [
        'bump-attempt',
        TASK,
        'review',
        '--review-type',
        reviewType ?? 'general',
        '--engine',
        engine,
      ]);
      expect(bump.status, bump.stderr).toBe(0);
      expect(trustedTaskState(fx)?.attempts['code']).toBe(1);

      const result = runScript(
        script,
        ['review', TASK, '--base', fx.baseSha, ...reviewArgs, '--confirm-round', baseline],
        fx.env,
      );
      const diagnostic = `${reviewType ?? 'default review type'}\n${result.stderr}`;
      expect(result.status, diagnostic).toBe(2);
      const state = trustedTaskState(fx);
      expect(state?.attempts['code'], diagnostic).toBe(0);
      expect(state?.pending_bumps.at(-1), diagnostic).toMatchObject({
        kind: 'code',
        engine,
        outcome: 'refused',
      });
      expect(existsSync(join(fx.log, 'argv.nul')), diagnostic).toBe(false);
    }
  },
);
