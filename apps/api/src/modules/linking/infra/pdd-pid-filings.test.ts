// Unit tests of the Pinduoduo per-pid filing store without a database (B1-06zi, BR-ID-22): Kysely
// runs on a scripted driver that records each compiled statement. They pin the statement shapes:
// the lookup is keyed by (app_id, user_id, pid) on the executor passed in, and the insert is
// insert-if-absent on that key with filed_at from the caller and no SQL clock. The SQL itself runs
// against PostgreSQL in the rule tests (test/spec/linking/pdd-pid-filings).
import type { DB } from '@couli/db';
import {
  Kysely,
  PostgresAdapter,
  PostgresIntrospector,
  PostgresQueryCompiler,
  type CompiledQuery,
  type DatabaseConnection,
  type Driver,
  type QueryResult,
} from 'kysely';
import { expect, it } from 'vitest';
import { hasPddPidFiling, recordPddPidFiling } from './pdd-pid-filings.ts';

const APP = 'couli';
const USER = '019a0000-0000-7000-8000-0000000000a1';
const ACCOUNT = '019a0000-0000-7000-8000-0000000000b1';
const PID = 'synthetic-pdd-self-buy';
const NOW = new Date('2026-11-09T02:00:00.000Z');

function setup(rows: readonly Record<string, unknown>[] = []) {
  const statements: CompiledQuery[] = [];
  const connection: DatabaseConnection = {
    executeQuery<R>(compiled: CompiledQuery): Promise<QueryResult<R>> {
      statements.push(compiled);
      return Promise.resolve({ rows, numAffectedRows: 0n } as unknown as QueryResult<R>);
    },
    async *streamQuery() {
      throw new Error('not used');
    },
  };
  const driver: Driver = {
    init: async () => undefined,
    acquireConnection: async () => connection,
    beginTransaction: async () => undefined,
    commitTransaction: async () => undefined,
    rollbackTransaction: async () => undefined,
    releaseConnection: async () => undefined,
    destroy: async () => undefined,
  };
  const db = new Kysely<DB>({
    dialect: {
      createAdapter: () => new PostgresAdapter(),
      createDriver: () => driver,
      createIntrospector: (kysely) => new PostgresIntrospector(kysely),
      createQueryCompiler: () => new PostgresQueryCompiler(),
    },
  });
  return { db, statements };
}

it('[AC-B1-06zi] the filing lookup is keyed by (app_id, user_id, pid)', async () => {
  const none = setup();
  expect(await hasPddPidFiling(none.db, { appId: APP, userId: USER, pid: PID })).toBe(false);
  expect(none.statements).toHaveLength(1);
  const [lookup] = none.statements;
  expect(lookup!.sql).toContain('from "union_pdd_pid_filings"');
  expect(lookup!.sql).toMatch(/"app_id" = \$1 and "user_id" = \$2 and "pid" = \$3/);
  expect(lookup!.parameters).toEqual([APP, USER, PID]);

  const found = setup([{ id: 'x' }]);
  expect(await hasPddPidFiling(found.db, { appId: APP, userId: USER, pid: PID })).toBe(true);
});

it('[AC-B1-06zi] the filing insert is insert-if-absent with the caller clock reading', async () => {
  const { db, statements } = setup();
  await recordPddPidFiling(db, {
    appId: APP,
    userId: USER,
    pid: PID,
    unionAccountId: ACCOUNT,
    filedAt: NOW,
  });
  expect(statements).toHaveLength(1);
  const [insert] = statements;
  expect(insert!.sql).toMatch(/^insert into "union_pdd_pid_filings"/);
  expect(insert!.sql).toContain('on conflict ("app_id", "user_id", "pid") do nothing');
  expect(insert!.sql).not.toMatch(/now\(\)|current_timestamp/i);
  expect(insert!.parameters).toEqual(expect.arrayContaining([APP, USER, PID, ACCOUNT, 'pdd', NOW]));
  // The id is generated by the application (a UUID v7 of the filing instant).
  expect(insert!.parameters[0]).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-/);
});

it('[AC-B1-06zi] filed_at and created_at both take the injected clock reading, never now()', async () => {
  const { db, statements } = setup();
  await recordPddPidFiling(db, {
    appId: APP,
    userId: USER,
    pid: PID,
    unionAccountId: ACCOUNT,
    filedAt: NOW,
  });
  const [insert] = statements;
  const columns = /^insert into "union_pdd_pid_filings" \(([^)]*)\) values \(([^)]*)\)/.exec(
    insert!.sql,
  );
  expect(columns).not.toBeNull();
  const names = columns![1]!.split(',').map((c) => c.trim().replaceAll('"', ''));
  const placeholders = columns![2]!.split(',').map((v) => v.trim());
  const valueOf = (column: string): unknown => {
    const index = names.indexOf(column);
    expect(index).toBeGreaterThanOrEqual(0);
    const placeholder = /^\$(\d+)$/.exec(placeholders[index]!);
    expect(placeholder).not.toBeNull();
    return insert!.parameters[Number(placeholder![1]) - 1];
  };
  expect(valueOf('filed_at')).toBe(NOW);
  expect(valueOf('created_at')).toBe(NOW);
  expect(insert!.sql).not.toMatch(/now\(\)|current_timestamp|default/i);
});
